#!/usr/bin/env python3
"""Build the data note: regenerate the tables from the CSVs as LaTeX fragments, stamp the version, compile twice."""
import csv, subprocess, re, datetime, zoneinfo
from pathlib import Path
HERE = Path(__file__).resolve().parent
tag = datetime.datetime.now(zoneinfo.ZoneInfo('America/Toronto')).strftime('%Y-%m-%d-%H-%M-%S')

def rows(name):
    with open(HERE / name, newline='', encoding='utf-8') as fh:
        return list(csv.DictReader(fh))

def esc(s):
    return str(s).replace('&', '\\&').replace('%', '\\%').replace('_', '\\_').replace('#', '\\#')

def num(s):
    try:
        f = float(s); return str(int(f)) if f == int(f) else f'{f:g}'
    except ValueError:
        return s

NAMES = {'CHRISTOPHE COLOMB': 'Christophe-Colomb', 'ST ZOTIQUE': 'Saint-Zotique', 'ST ZOTIQUE E': 'Saint-Zotique Est', 'MISTRAL': 'Mistral', 'ST PIERRE': 'Saint-Pierre',
 'BERGE DU CANAL': 'berge du canal', 'MAURICE DUPLESSIS': 'Maurice-Duplessis', 'MARC AURELE FORTIN': 'Marc-Aurèle-Fortin', 'TILLEMONT': 'Tillemont', 'MARQUETTE': 'Marquette',
 'WELLINGTON': 'Wellington', 'DE LA MONTAGNE': 'de la Montagne', 'N-D': 'Notre-Dame', 'COTE DES NEIGES': 'Côte-des-Neiges', 'LINTON': 'Linton', 'AV PARC': 'av. du Parc',
 'RENE LEVESQUE': 'René-Lévesque', 'PEEL': 'Peel', 'ST DENIS': 'Saint-Denis', 'LAURIER': 'Laurier', 'DES CARRIERES': 'des Carrières', 'NAZARETH': 'Nazareth', 'ST DENIS FACE': 'Saint-Denis',
 'SHERBROOKE O': 'Sherbrooke Ouest', 'STANLEY': 'Stanley', 'LAJEUNESSE': 'Lajeunesse', 'LEGENDRE': 'Legendre', 'RIV DES PRAIRIES': 'Rivière-des-Prairies', 'DE LA MARTINIERE': 'de la Martinière',
 'IBERVILLE': 'Iberville', 'BD ROSEMONT': 'boul. Rosemont', 'MONSELET': 'Monselet', 'BRUXELLES': 'Bruxelles', 'BELANGER': 'Bélanger', '6E AV': '6e Avenue', 'AV DU PARC': 'av. du Parc',
 'AV DES PINS': 'av. des Pins', 'VOIE CAMILIEN HOUDE': 'voie Camillien-Houde', 'CREMAZIE': 'Crémazie', '23E AV': '23e Avenue', '19E AV': '19e Avenue', 'FORDEN CRESCENT': 'Forden Crescent (Westmount)',
 'FORDEN': 'Forden', 'AV PAPINEAU': 'av. Papineau', 'CH DE L ANSE A L ORME': "ch. de l'Anse-à-l'Orme", 'BD GOUIN O': 'boul. Gouin Ouest', 'PARC DU AVEN': 'av. du Parc', 'MONT-ROYAL DU O AVEN': 'av. du Mont-Royal Ouest',
 'NOTRE-DAME RUE': 'Notre-Dame', 'ST-PIERRE AVEN': 'Saint-Pierre', 'ST-LAURENT BOUL': 'boul. Saint-Laurent', 'LIEGE DE O RUE': 'de Liège Ouest'}
def name(s):
    s = s.strip(); return NAMES.get(s, s.title())
T = rows('cyclist_fatality_locations_2012-2021.csv'); S = rows('summary_earlier_fatal.csv'); Q = rows('summary_earlier_record.csv'); TT = rows('terrebonne_same_scale_2012-2021.csv')
out = []
out.append('% generated by build.py from the CSVs; do not edit\n')
# table of the 31
out.append(r'{\footnotesize\setlength{\tabcolsep}{3.5pt}\begin{longtable}{@{}l p{3.9cm} l r c c c@{}}' '\n'
           r'\caption{The 31 collisions with a cyclist killed, SPVM open data 2012--2021, and the earlier record at each location. '
           r'\emph{Earlier fatal}: number of earlier fatal collisions of any kind on the same street name / at the same intersection / within 100\,m / within 250\,m. '
           r'\emph{Within 100 m} and \emph{within 250 m}: earlier collisions of all kinds / with an injury (fatal, severe or light) / involving a bicycle / with a pedestrian victim. '
           r'Years = years of record before the date, from January 1, 2012. $\dagger$ = location flagged imprecise in the City file.}\label{tab:31}\\' '\n'
           r'\toprule Date & Location & Other vehicle & Years & Earlier fatal & Within 100\,m & Within 250\,m\\ \midrule \endfirsthead' '\n'
           r'\toprule Date & Location & Other vehicle & Years & Earlier fatal & Within 100\,m & Within 250\,m\\ \midrule \endhead' '\n'
           r'\bottomrule \endlastfoot' '\n')
for r in T:
    loc = esc(name(r['street'])) + (' / ' + esc(name(r['near'])) if r['near'] and r['near'] not in ('FACE', 'OPP') else '') + (', ' + esc(r['civic']) if r['civic'] and r['civic'] != 'nan' else '')
    if r['location_imprecise'] == 'True': loc += '$^\\dagger$'
    inj100 = int(r['d100_fatal']) + int(r['d100_severe']) + int(r['d100_light']); inj250 = int(r['d250_fatal']) + int(r['d250_severe']) + int(r['d250_light'])
    out.append(f"{r['date']} & {loc} & {esc(r['other_vehicle']).replace('car/light truck', 'car or light truck')} & {float(r['years_of_record']):.1f} & {r['name_fatal_any']} / {r['intersection_fatal_any']} / {r['d100_fatal_any']} / {r['d250_fatal_any']} & "
               f"{r['d100_n']} / {inj100} / {r['d100_bike']} / {r['d100_ped']} & {r['d250_n']} / {inj250} / {r['d250_bike']} / {r['d250_ped']}\\\\\n")
out.append(r'\end{longtable}}' '\n\n')
# summary earlier fatal
out.append(r'\begin{table}[h]\centering\caption{Of the 31 collisions with a cyclist killed: whether a fatal collision of any kind had been recorded earlier at the same location, by definition.}\label{tab:fatal}' '\n'
           r'\begin{tabular}{@{}l r r@{}}\toprule Definition of the same location & With an earlier fatal collision & Without\\ \midrule' '\n')
for r in S:
    out.append(f"{esc(r['definition'])} & {r['with an earlier fatal collision']} & {r['without']}\\\\\n")
out.append(r'\bottomrule\end{tabular}\end{table}' '\n\n')
# summary record
for label in dict.fromkeys(r['cases'] for r in Q):
    sub = [r for r in Q if r['cases'] == label]
    out.append(r'\begin{table}[h]\centering\caption{Earlier record at the location, ' + esc(label) + f' (n = {sub[0]["n"]}): number of cases with none, and the median (first and third quartile) of the count; the last column is the median of the count divided by the years of record.}}' + '\n'
               r'\begin{tabular}{@{}l l r r r@{}}\toprule Radius & Measure & None & Median (Q1--Q3) & Median per year\\ \midrule' '\n')
    for r in sub:
        out.append(f"{r['radius_m']}\\,m & {esc(r['measure'])} & {r['zero']} & {num(r['median'])} ({num(r['q1'])}--{num(r['q3'])}) & {num(r['median_per_year'])}\\\\\n")
    out.append(r'\bottomrule\end{tabular}\end{table}' '\n\n')
# Terrebonne
out.append(r'\begin{table}[htbp]\centering\caption{Rue de Terrebonne measured the same way (SPVM open data 2012--2021). Columns as in Table~\ref{tab:31}, plus the fatal count; the last two rows count the whole street.}\label{tab:terrebonne}' '\n'
           r'\footnotesize\setlength{\tabcolsep}{4pt}\begin{tabular}{@{}p{5.6cm} r l l@{}}\toprule Location & Years & 100\,m: all / inj. / bike / ped / fatal & 250\,m: all / inj. / bike / ped / fatal\\ \midrule' '\n')
def cell(r, p):
    if r.get(f'{p}_n', '') == '': return ''
    inj = int(float(r[f'{p}_fatal'])) + int(float(r[f'{p}_severe'])) + int(float(r[f'{p}_light']))
    return f"{num(r[f'{p}_n'])} / {inj} / {num(r[f'{p}_bike'])} / {num(r[f'{p}_ped'])} / {num(r[f'{p}_fatal_any'])}"
for r in TT:
    if r.get('street_n', ''):
        out.append(f"{esc(r['location'])} & {num(r['years_of_record'])} & \\multicolumn{{2}}{{l}}{{whole street: {cell(r, 'street')}}}\\\\\n")
    else:
        out.append(f"{esc(r['location'])} & {num(r['years_of_record'])} & {cell(r, 'd100')} & {cell(r, 'd250')}\\\\\n")
out.append(r'\bottomrule\end{tabular}\end{table}' '\n')
(HERE / 'tables_generated.tex').write_text(''.join(out), encoding='utf-8')
tex = HERE / 'cyclist_fatality_locations_note_en.tex'
s = tex.read_text(encoding='utf-8'); s = re.sub(r'\\newcommand\{\\docversion\}\{[^}]*\}', r'\\newcommand{\\docversion}{%s}' % tag, s); tex.write_text(s, encoding='utf-8')
for _ in range(2):
    subprocess.run(['pdflatex', '-interaction=nonstopmode', '-halt-on-error', tex.name], cwd=HERE, check=True, stdout=subprocess.DEVNULL)
print('built', tex.with_suffix('.pdf').name, 'version', tag)
